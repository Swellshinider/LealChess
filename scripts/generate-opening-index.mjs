import { writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Chess } from 'chess.js';
import { format } from 'prettier';

const sourceRevision = '51b886249b9e418498d25b6e39b926c3de99c29a';
const volumes = ['a', 'b', 'c', 'd', 'e'];
const positions = new Set();
const openings = new Map();

for (const volume of volumes) {
  const url = `https://raw.githubusercontent.com/lichess-org/chess-openings/${sourceRevision}/${volume}.tsv`;
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Could not download ${url}: ${response.status}`);

  const rows = (await response.text()).trim().split('\n').slice(1);
  for (const row of rows) {
    const [eco, name, rawPgn] = row.replace(/\r$/, '').split('\t');
    const pgn = rawPgn?.trim();
    if (!eco || !name || !pgn) continue;
    const chess = new Chess();
    chess.loadPgn(pgn);
    const history = chess.history({ verbose: true });
    for (const move of history) {
      positions.add(positionKey(move.after));
    }
    const finalPosition = history.at(-1)?.after;
    if (finalPosition) {
      openings.set(positionKey(finalPosition), { eco, name });
    }
  }
}

const output = await format(
  `// Generated by scripts/generate-opening-index.mjs.
// Source: lichess-org/chess-openings@${sourceRevision} (CC0-1.0).
export const OPENING_POSITION_DATA = ${JSON.stringify([...positions].sort().join('\n'))};
export const OPENING_NAME_DATA = ${JSON.stringify(
    [...openings.entries()]
      .sort(([left], [right]) => left.localeCompare(right))
      .map(([position, opening]) => `${position}\t${opening.eco}\t${opening.name}`)
      .join('\n'),
  )};
`,
  { parser: 'typescript', printWidth: 100, singleQuote: true },
);
const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(
  scriptDirectory,
  '../src/app/core/openings/opening-positions.generated.ts',
);
await writeFile(outputPath, output, 'utf8');
console.log(
  `Wrote ${positions.size} book positions and ${openings.size} named openings to ${outputPath}`,
);

function positionKey(fen) {
  return fen.split(' ').slice(0, 4).join(' ');
}
